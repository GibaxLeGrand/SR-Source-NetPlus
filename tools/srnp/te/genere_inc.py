"""La carte US -> TE en table C++ pour le runner (srnp_game_te.inc) : des plages {début US, fin US, début TE}.

python -I genere_inc.py <suites.txt> <donnees.txt> <manuel.txt> <sortie.inc>

- code : les suites de carte.py (formes égales mot à mot) ;
- données : les paires de carte.py regroupées en plages de même écart (une paire seule couvre 0x100 octets ;
  deux paires voisines de même écart couvrent tout l'intervalle, jusqu'à 0x2000) ;
- manuel.txt : « <début US> <fin US> <début TE> # pourquoi », prioritaire (trouvé à la main).
Rien du jeu n'y est : des adresses seulement.
"""
import sys


def main():
    suites_p, donnees_p, manuel_p, sortie = sys.argv[1:5]
    plages = []
    for l in open(suites_p):
        a, b, n = l.split()
        a, b, n = int(a, 16), int(b, 16), int(n)
        plages.append((a, a + 4 * n, b, "code"))
    paires = []
    for l in open(donnees_p):
        a, b, n = l.split()
        a, b = int(a, 16), int(b, 16)
        if 0x80003100 <= a < 0x81800000 and 0x80003100 <= b < 0x81800000:  # des adresses, hors mémoire basse
            paires.append((a, b))
    paires.sort()
    k = 0
    while k < len(paires):
        a, b = paires[k]
        ecart = b - a
        fin = a + 4
        j = k + 1
        while j < len(paires) and paires[j][1] - paires[j][0] == ecart and paires[j][0] - fin <= 0x2000:
            fin = paires[j][0] + 4
            j += 1
        suivant = paires[j][0] if j < len(paires) else 0xFFFFFFFF
        fin = min(max(fin, a + 0x100), suivant)
        plages.append((a, fin, b, "donnees"))
        k = j
    manuels = []
    for l in open(manuel_p, encoding="utf-8"):
        l = l.split("#")[0].strip()
        if l:
            a, f, b = (int(x, 16) for x in l.split())
            manuels.append((a, f, b, "manuel"))
    # Les plages manuelles d'abord, puis le reste sans chevauchement.
    finales = []
    def chevauche(a, f):
        return any(a < f2 and a2 < f for a2, f2, _, _ in finales)
    # Le code avant les données (des paires de données tombent dans le code : des pointeurs de fonctions).
    for p in manuels + sorted(plages, key=lambda p: (p[3] != "code", -(p[1] - p[0]))):
        if not chevauche(p[0], p[1]):
            finales.append(p)
    finales.sort()
    with open(sortie, "w", newline="\n") as f:
        f.write("// Generated by work/te/adresses/genere_inc.py from the two games' code (2026-11-26): Sonic Riders US\n")
        f.write("// (GXEE8P, _Main.rel at 0x803FBD00) -> Tournament Edition 2.4.6.1 (GXSRTE). Addresses only.\n")
        f.write("// {US start, US end, TE start}\n")
        for a, fin, b, genre in finales:
            f.write(f"{{0x{a:08X}u, 0x{fin:08X}u, 0x{b:08X}u}},  // {genre}\n")
    print(f"{len(finales)} plages ({sum(1 for p in finales if p[3] == 'code')} code, "
          f"{sum(1 for p in finales if p[3] == 'donnees')} données, {len(manuels)} manuelles)")


main()
